// Copies the tested example sources into the docs page, so the code shown in
// /docs is exactly the code that the test suite and the live E2E run use.
//   contracts/src/examples/DiceRoller.sol   (tested in contracts/test/DiceRoller.t.sol)
//   bot/examples/request-randomness.mjs     (run end-to-end against testnet)
// Runs before every build; skipped if the sources aren't present (e.g. a
// host that only checks out web/), in which case the committed copy is used.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const sources = {
  solidity: join(root, "contracts/src/examples/DiceRoller.sol"),
  js: join(root, "bot/examples/request-randomness.mjs"),
};
if (!Object.values(sources).every(existsSync)) {
  console.log("sync-snippets: sources not found, keeping committed snippets");
  process.exit(0);
}
const out = Object.entries(sources)
  .map(([k, f]) => `export const ${k}Example = ${JSON.stringify(readFileSync(f, "utf8"))};`)
  .join("\n\n");
writeFileSync(
  join(root, "web/app/docs/snippets.ts"),
  `// GENERATED by web/scripts/sync-snippets.mjs — do not edit by hand.\n\n${out}\n`,
);
console.log("sync-snippets: docs snippets updated");
